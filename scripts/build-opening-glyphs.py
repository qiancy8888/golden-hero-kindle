#!/usr/bin/env python3
"""Build the Golden Hero Opening Glyphs subset from Unifont 16.0.04 .hex.gz."""
import argparse
import gzip
from pathlib import Path

GAME = Path(__file__).resolve().parent.parent / "game"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("hex_gz", type=Path)
    args = parser.parse_args()

    text = "".join(path.read_text(encoding="utf-8") for path in sorted(GAME.glob("*.cpp")))
    codes = set(range(0x20, 0x7f)) | {ord(char) for char in text if ord(char) > 0x7f}
    rows = {}
    with gzip.open(args.hex_gz, "rt", encoding="ascii") as source:
        for line in source:
            code, bitmap = line.strip().split(":")
            value = int(code, 16)
            if value in codes:
                rows[value] = bitmap
    missing = codes - rows.keys()
    if missing:
        parser.exit(2, "Missing font code points: " + ", ".join(f"U+{code:04X}" for code in sorted(missing)))

    lines = ["// Golden Hero Opening Glyphs. Generated by scripts/build-opening-glyphs.py.",
             "// Derived from GNU Unifont 16.0.04. See FONT-OFL.txt."]
    for code, bitmap in sorted(rows.items()):
        digits = len(bitmap) // 16
        if digits not in (2, 4):
            parser.exit(2, f"Invalid bitmap for U+{code:04X}\n")
        hex_rows = ", ".join(f"0x{bitmap[i:i + digits]}" for i in range(0, len(bitmap), digits))
        lines.append(f"    {{0x{code:04X}, {digits * 4}, {{{hex_rows}}}}},")
    (GAME / "opening_glyphs.inc").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
